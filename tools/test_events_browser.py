"""Agenda no Chrome: calendário, formulário, avisos e navegação em celular."""
import argparse
from datetime import datetime, timedelta, timezone
import json
import hashlib
from pathlib import Path
from playwright.sync_api import sync_playwright
import test_portal as portal
from test_runtime_fixes import test_server

parser = argparse.ArgumentParser()
parser.add_argument('--php', required=True)
parser.add_argument('--browser', required=True)
args = parser.parse_args()
checks, errors = [], []

def check(condition, label):
    assert condition, label
    checks.append(label)

with test_server(Path(args.php)) as (base, db, config, storage, manifest, scratch, env):
    member = portal.Client(base)
    member.login('aluno', portal.MEMBER_PASSWORD)
    token = member.csrf()
    today = datetime.now(timezone(timedelta(hours=-3))).date()
    subject, subject_name = db.execute('SELECT id, name FROM hc_portal_subjects ORDER BY id LIMIT 1').fetchone()
    for priority, title in [('baixa', 'Revisar os estudos'), ('media', 'Entregar atividade'), ('urgente', 'Prova de Banco de Dados')]:
        member.request('/agenda/eventos/criar', dict(csrf=token, title=title, description='Anotações do evento', event_date=str(today), all_day='1', priority=priority, subject_id=subject, category='faculdade'))
    with sync_playwright() as pw:
        browser = pw.chromium.launch(executable_path=args.browser, headless=True)
        for width in [1440, 390, 320]:
            page = browser.new_page(viewport=dict(width=width, height=1000))
            page.on('pageerror', lambda error: errors.append(str(error)))
            page.goto(base + '/entrar')
            page.get_by_label('Usuário', exact=True).fill('aluno')
            page.get_by_label('Senha', exact=True).fill(portal.MEMBER_PASSWORD)
            page.get_by_role('button', name='Entrar no portal').click()
            page.wait_for_url('**/biblioteca')
            if width <= 1000:
                page.locator('[data-sidebar-toggle]').click()
            page.locator('.main-nav a').filter(has_text='Agenda').click()
            page.wait_for_url('**/agenda')
            check(page.locator('[data-library-page]').count() == 0, f'{width}: navegação biblioteca para agenda funciona')
            check(page.locator('.calendar-day').count() == 42, f'{width}: calendário mensal completo')
            check(page.locator('[data-event-row]').count() == 3, f'{width}: lista do dia selecionado mostra os três eventos')
            check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'{width}: calendário sem overflow horizontal')
            page.screenshot(path=str(portal.ROOT / f'artifacts/events-calendar-{width}.png'), full_page=True)
            page.get_by_role('link', name='Próximo mês', exact=True).click()
            check(page.locator('[data-event-row]').count() == 0, f'{width}: próximo mês altera dia e lista')
            page.goto(base + '/agenda')
            page.locator('[data-notification-menu] > summary').click()
            check(page.locator('.notification-popover .notification-item').count() == 3, f'{width}: sino lista avisos do usuário')
            check(page.locator('.notification-popover').evaluate('(e) => e.getBoundingClientRect().left >= 0 && e.getBoundingClientRect().right <= innerWidth'), f'{width}: avisos cabem na tela')
            page.keyboard.press('Escape')
            check(not page.locator('[data-notification-menu]').evaluate('(e) => e.open'), f'{width}: Escape fecha avisos')
            page.get_by_role('link', name='Novo evento', exact=True).click()
            page.locator('#detail-dialog [data-event-form]').wait_for()
            check(page.url.endswith('/agenda'), f'{width}: novo evento abre em modal sem trocar de página')
            check(page.locator('[data-event-times]').is_hidden(), f'{width}: dia inteiro oculta horários')
            check(page.locator('[name=starts_at]').is_disabled(), f'{width}: dia inteiro desativa horários')
            page.get_by_label('Título', exact=True).fill('Evento do navegador ' + str(width))
            page.get_by_label('Descrição', exact=False).fill('Linha 1\nLinha 2')
            check(page.locator('[name=category]').evaluate('(e) => e.required'), f'{width}: categoria obrigatória no formulário')
            check(page.locator('[name=category] option').count() == 8, f'{width}: exatamente sete categorias e uma opção vazia')
            page.locator('[name=category] + .select2 .select2-selection').click()
            page.get_by_role('option', name='Estudo independente', exact=True).click()
            page.locator('[name=all_day] + .select2 .select2-selection').click()
            page.get_by_role('option', name='Com horário de início e fim', exact=True).click()
            check(page.locator('[data-event-times]').is_visible(), f'{width}: modo com horário exibe campos')
            page.get_by_label('Início', exact=True).fill('09:15')
            page.get_by_label('Fim', exact=True).fill('10:45')
            page.locator('[name=subject_id] + .select2 .select2-selection').click()
            page.locator('.select2-search__field').fill(subject_name)
            page.get_by_role('option', name=subject_name, exact=True).click()
            page.get_by_label('Data', exact=True).fill(str(today + timedelta(days=2)))
            check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'{width}: formulário sem overflow horizontal')
            page.get_by_role('button', name='Salvar evento', exact=True).click()
            page.locator('#detail-dialog .event-detail').wait_for()
            created = db.execute('SELECT id, starts_at, ends_at, subject_id FROM hc_portal_events WHERE title = ?', ('Evento do navegador ' + str(width),)).fetchone()
            event_id = created[0]
            check(db.execute('SELECT category FROM hc_portal_events WHERE id = ?', (event_id,)).fetchone()[0] == 'estudo_independente', f'{width}: categoria escolhida persiste')
            check(created[1:] == ('09:15', '10:45', subject), f'{width}: criação no navegador persiste horários e matéria')
            page.get_by_role('link', name='Editar', exact=True).click()
            check(page.locator('[name=category]').input_value() == 'estudo_independente', f'{width}: edição recupera categoria')
            page.locator('[name=category] + .select2 .select2-selection').click()
            page.get_by_role('option', name='Evento acadêmico', exact=True).click()
            page.locator('[name=all_day] + .select2 .select2-selection').click()
            page.get_by_role('option', name='Dia inteiro, sem horário', exact=True).click()
            page.get_by_role('button', name='Salvar evento', exact=True).click()
            page.locator('#detail-dialog .event-detail').wait_for()
            check('Categoria: Evento acadêmico' in page.locator('.event-detail').inner_text(), f'{width}: edição exibe categoria atualizada')
            check(db.execute('SELECT starts_at, ends_at FROM hc_portal_events WHERE id = ?', (event_id,)).fetchone() == (None, None), f'{width}: edição para dia inteiro limpa horários')
            page.get_by_role('button', name='Excluir evento', exact=True).click()
            page.locator('#delete-event-dialog [name=confirm]').check()
            page.locator('#delete-event-dialog [type=submit]').click()
            page.wait_for_url('**/agenda?*')
            check(db.execute('SELECT COUNT(*) FROM hc_portal_events WHERE id = ?', (event_id,)).fetchone()[0] == 0, f'{width}: exclusão com confirmação funciona')
            page.goto(base + '/agenda')
            page.locator('[data-theme-toggle]').click()
            check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'{width}: tema alternativo sem overflow')
            page.screenshot(path=str(portal.ROOT / f'artifacts/events-calendar-alternate-{width}.png'), full_page=True)
            page.close()
        page = browser.new_page(viewport=dict(width=1440, height=1000))
        page.goto(base + '/entrar')
        page.get_by_label('Usuário', exact=True).fill('aluno')
        page.get_by_label('Senha', exact=True).fill(portal.MEMBER_PASSWORD)
        page.get_by_role('button', name='Entrar no portal').click()
        page.wait_for_url('**/biblioteca')
        page.locator('[data-notification-menu] > summary').click()
        page.locator('.notification-popover .notification-item button').first.click()
        page.wait_for_url('**/notificacoes')
        check(page.locator('.notification-list .notification-item.unread').count() == 2, 'Marcar aviso pelo sino mantém os demais pendentes')
        page.goto(base + '/biblioteca')
        member.request('/agenda/eventos/criar', dict(csrf=token, title='Aviso após navegação', event_date=str(today), all_day='1', priority='media', subject_id='', category='curso'))
        if page.locator('[data-sidebar-toggle]').get_attribute('aria-expanded') != 'true':
            page.locator('[data-sidebar-toggle]').click()
        page.locator('.subject-nav a').first.click()
        page.wait_for_url('**/materias/*')
        page.wait_for_function("() => document.querySelector('[data-notification-menu] .notification-count')?.textContent === '3'")
        check(True, 'Navegação dinâmica da biblioteca atualiza sino')
        check(page.locator('[data-library-page]').count() == 1, 'Biblioteca conserva navegação dinâmica')
        check(not errors, 'Nenhum erro JavaScript no navegador')
        page.close()
        browser.close()
paths = ['portal/src/agenda-views.php', 'portal/src/views.php', 'portal/assets/app.css', 'portal/assets/app.js']
(portal.ROOT / 'artifacts/events-browser-verification.json').write_text(json.dumps(dict(status='verified', checks=len(checks), results=checks, tested_at=datetime.now(timezone.utc).isoformat(), sha256={path: hashlib.sha256((portal.ROOT / path).read_bytes()).hexdigest() for path in paths}), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print('Agenda Chrome:', len(checks), 'verificações aprovadas')
